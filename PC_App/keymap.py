_DIGIT_USAGES = {
    "1": 0x1E,
    "2": 0x1F,
    "3": 0x20,
    "4": 0x21,
    "5": 0x22,
    "6": 0x23,
    "7": 0x24,
    "8": 0x25,
    "9": 0x26,
    "0": 0x27,
}


def keysym_to_usage(keysym: str) -> int | None:
    key = keysym.lower()

    if key in _NAMED_KEYS:
        return _NAMED_KEYS[key]
    if len(key) == 1 and key in string.ascii_lowercase:
        return 0x04 + ord(key) - ord("a")
    if keysym in _DIGIT_USAGES:
        return _DIGIT_USAGES[keysym]
    if key.startswith("f") and key[1:].isdigit():
        number = int(key[1:])
        if 1 <= number <= 24:
            return 0x3A + number - 1 if number <= 12 else 0x68 + number - 13
    return None
